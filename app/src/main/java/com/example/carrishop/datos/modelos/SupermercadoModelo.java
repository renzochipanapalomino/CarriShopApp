package com.example.carrishop.datos.modelos;

public class SupermercadoModelo {
    public int id;
    public String nombre;
    public int logoRes;
    public String descripcion;

    public SupermercadoModelo(int id, String nombre, int logoRes, String descripcion) {
        this.id = id;
        this.nombre = nombre;
        this.logoRes = logoRes;
        this.descripcion = descripcion;
    }
}
